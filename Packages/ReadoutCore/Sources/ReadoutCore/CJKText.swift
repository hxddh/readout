    static func contains(_ ranges: [ClosedRange<UInt32>], _ v: UInt32) -> Bool {
        var lo = 0, hi = ranges.count - 1
        while lo <= hi {
            let mid = (lo + hi) / 2
            if v < ranges[mid].lowerBound { hi = mid - 1 } else if v > ranges[mid].upperBound { lo = mid + 1 } else { return true }
        }
        return false
    }

    static func isCJK(_ v: UInt32) -> Bool { v >= 0x1100 && contains(cjkRanges, v) }
    static func isHangul(_ v: UInt32) -> Bool { v >= 0x1100 && contains(hangulRanges, v) }
    /// Wide CJK text a line break between two of which is no space (CSS Text
    /// segment break rules: East Asian Width F, W or H, not Hangul).
    static func isWideNonHangul(_ v: UInt32) -> Bool { isCJK(v) && !isHangul(v) }

    static func isASCIIPunctuation(_ v: UInt32) -> Bool {
        (0x21...0x2F).contains(v) || (0x3A...0x40).contains(v) || (0x5B...0x60).contains(v) || (0x7B...0x7E).contains(v)
    }

    /// Punctuation to cmark-gfm.
    static func isPunctuation(_ v: UInt32) -> Bool {
        v < 0x80 ? isASCIIPunctuation(v) : contains(punctuationRanges, v)
    }

    /// White space to cmark-gfm (`cmark_utf8proc_is_space`).
    static func isSpace(_ v: UInt32) -> Bool {
        v == 9 || v == 10 || v == 12 || v == 13 || v == 32 || v == 0xA0 || v == 0x1680
            || (0x2000...0x200A).contains(v) || v == 0x202F || v == 0x205F || v == 0x3000
    }

    /// Variation selectors other than the emoji one (U+FE00-U+FE0E).
    static func isTextVariationSelector(_ v: UInt32) -> Bool { (0xFE00...0xFE0E).contains(v) }
    /// Ideographic variation selectors (U+E0100-U+E01EF).
    static func isIdeographicVariationSelector(_ v: UInt32) -> Bool { (0xE0100...0xE01EF).contains(v) }
}
